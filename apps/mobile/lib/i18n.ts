export function useMobileI18n() {
  const { profile } = useSession();
  const locale = profile?.user.locale ?? "uk";
  const dictionary = locale === "en" ? en : uk;
  const t = useCallback(
    (key: keyof typeof en) => dictionary[key],
    [dictionary],
  );
  const tr = useCallback(
    (ukrainian: string, english: string) =>
      locale === "en" ? english : ukrainian,
    [locale],
  );
  return {
    locale,
    t,
    tr,
  };
}
