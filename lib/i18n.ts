export type TranslationKey = keyof typeof uk;

export function normalizeLocale(value: string | null | undefined): Locale {
  return value === "en" ? "en" : DEFAULT_LOCALE;
}

export function translate(locale: Locale, key: TranslationKey | string) {
  if (locale === "en") return key;
  return uk[key as TranslationKey] ?? key;
}

/** Format a numeric label with a consistent plural form across the UI. */
export function formatCount(
  locale: Locale,
  value: number,
  ukForms: { one: string; few: string; many: string },
  enForms: { one: string; many: string },
) {
  const category = new Intl.PluralRules(
    locale === "uk" ? "uk-UA" : "en-GB",
  ).select(value);
  const word =
    locale === "uk"
      ? category === "one"
        ? ukForms.one
        : category === "few"
          ? ukForms.few
          : ukForms.many
      : category === "one"
        ? enForms.one
        : enForms.many;
  return `${value} ${word}`;
}
